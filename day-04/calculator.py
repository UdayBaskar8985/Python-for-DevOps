def add(num1, num2):
    addition = num1+num2
    return addition

def sub(num1, num2):
    subtraction = num1 - num2
    return subtraction
    
def mul(num1, num2):
    multiplication = num1*num2
    return multiplication
    
    
print(add(10,20))
print(sub(200,100))
print(mul(10,10))